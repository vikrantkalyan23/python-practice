# Operator Precedence

# 1. ()
#    Parentheses
# 2. **
#    Exponentiation
# 3. *, /, //, %
#    Multiplication / division
# 4. +, -
#    Addition / subtraction
# 5. <, <=, >, >=, ==, !=
#    Comparisons
# 6. not
# 7. and
# 8. or

result = 10 + (5 * 2)
print(result)

age = 18
is_active = True
result = (age >= 18) and is_active
print(result)