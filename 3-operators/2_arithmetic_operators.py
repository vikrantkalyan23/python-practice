# Arithmetic Operators (Arithmetic operators are used for mathematical calculations)

a = 10
b = 5

# + Addition
print("Addition : ", a + b)

# - Subtraction
print("Subtraction : ", a - b)

# * Multiplication
print("Multiplication : ", a * b)

# / Division
print("Division : ", a / b)

# // Floor Division (Floor division returns the quotient rounded down)
print("Floor Division : ", a / b)

# % Modulus (Returns the remainder)
print("Remainder : ", 10 % 3)
# Very common use: even/odd
number = 10
if number % 2 == 0:
    print("Even")
else:
    print("Odd")

# ** Exponentiation (Used for powers)
print("Exponentiation : ", 2**3)

# Arithmetic Operator Summary

# | Operator | Meaning        |   Example |     Result |
# | -------- | -------------- | --------: | ---------: |
# | `+`      | Addition       |  `10 + 3` |       `13` |
# | `-`      | Subtraction    |  `10 - 3` |        `7` |
# | `*`      | Multiplication |  `10 * 3` |       `30` |
# | `/`      | Division       |  `10 / 3` | `3.333...` |
# | `//`     | Floor division | `10 // 3` |        `3` |
# | `%`      | Remainder      |  `10 % 3` |        `1` |
# | `**`     | Power          | `10 ** 3` |     `1000` |
