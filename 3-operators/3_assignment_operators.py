# Assignment operators are used to assign or update values

# | Operator | Example   | Equivalent   |
# | -------- | --------- | ------------ |
# | `=`      | `x = 10`  | Assign       |
# | `+=`     | `x += 2`  | `x = x + 2`  |
# | `-=`     | `x -= 2`  | `x = x - 2`  |
# | `*=`     | `x *= 2`  | `x = x * 2`  |
# | `/=`     | `x /= 2`  | `x = x / 2`  |
# | `//=`    | `x //= 2` | `x = x // 2` |
# | `%=`     | `x %= 2`  | `x = x % 2`  |
# | `**=`    | `x **= 2` | `x = x ** 2` |

# = Assignment
count = 10
print(f"Count : {count}")

# +=
count += 5
print(f"Count : {count}")

# -=
count -= 5
print(f"Count : {count}")

# *=
price = 100
price *= 2
print("Price : ", price)

# /=
price /= 4
print("Price : ", price)

# //=
number = 10
number //= 3
print("Number : ", number)

# %=
number = 10
number %= 3
print("Number : ", number)

# **=
number = 10
number **= 3
print("Number : ", number)
