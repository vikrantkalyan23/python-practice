# Operators with Different Data Types

# Operators don't always behave the same way for different types

# For numbers:
print(10 + 20)

# For strings: (+ operator is doing concatenation for strings)
print("Hello " + "Python")


# String Multiplication
print("Python " * 3)

# List Operators (+ operator can combine lists)
first = [1, 2, 3]
second = [4, 5, 6]
result = first + second
print(result)

# * can repeat a list:
numbers = [1, 2]
print(numbers * 3)